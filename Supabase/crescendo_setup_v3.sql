-- ─── guest_set_email ────────────────────────────────────────────────────────
-- Captures an address a guest gives at the desk. Fills a BLANK only — never
-- overwrites an address already on file, so a typo cannot destroy good data.
-- Enforced here, not just in the UI.

CREATE OR REPLACE FUNCTION public.guest_set_email(p_pin text, p_id bigint, p_email text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_rows  int;
begin
  if not public.volunteer_pin_check(p_pin) then
    raise exception 'Invalid request';
  end if;

  -- Must look like an email. Nothing fancy, just a sanity check.
  if v_email = ''
     or position('@' in v_email) = 0
     or position('.' in split_part(v_email, '@', 2)) = 0
     or length(v_email) > 254 then
    raise exception 'Invalid request';
  end if;

  -- Only fills a blank. Never overwrites an address already on file.
  update public.registrations r
     set email = v_email
   where r.id = p_id
     and btrim(coalesce(r.email, '')) = '';

  get diagnostics v_rows = row_count;
  return v_rows > 0;
end;
$function$;


