-- ─── registrations ──────────────────────────────────────────────────────────
-- Column names match normaliseRow() in admin_crescendo.html exactly.
-- Do not rename.
--
-- email is NOT unique and NOT constrained to be non-empty:
--   * couples registering once share a single address; both must check in from
--     one lookup, and a unique constraint would hard-fail the whole batch insert
--   * guests who never gave an address have a blank email and are checked in by
--     row id through the volunteer page
--
-- table_number is TEXT, not INT — rosters contain values like "12A".

create table if not exists public.registrations (
  id             bigint generated by default as identity primary key,
  first_name     text not null default ''::text,
  last_name      text not null default ''::text,
  email          text not null,
  table_number   text not null default ''::text,
  room           text not null default ''::text,
  checked_in     boolean not null default false,
  check_in_time  timestamptz,
  checkin_method text
);

do $$
begin
  if not exists (select 1 from pg_constraint
                  where conname = 'registrations_email_normalised') then
    alter table public.registrations
      add constraint registrations_email_normalised
      check (email = lower(btrim(email)));
  end if;

  if not exists (select 1 from pg_constraint
                  where conname = 'registrations_checkin_method') then
    alter table public.registrations
      add constraint registrations_checkin_method
      check (checkin_method is null
             or checkin_method = any (array['self'::text, 'volunteer'::text]));
  end if;
end $$;

