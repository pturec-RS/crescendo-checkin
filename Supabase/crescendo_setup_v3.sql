       coalesce(nullif(string_agg(privilege_type, ', '), ''), 'NONE')
  from information_schema.role_table_grants
 where grantee = 'anon' and table_schema = 'public' and table_name = 'app_settings';

-- (b) Every function must be executable by BOTH roles. All seven rows true/true.
--     Checking only anon is what caused the 42501 incident in session #3.
select p.proname,
       has_function_privilege('anon', p.oid, 'EXECUTE')          as anon_ok,
       has_function_privilege('authenticated', p.oid, 'EXECUTE') as auth_ok
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public'
   and p.proname in ('volunteer_pin_check', 'guest_lookup', 'guest_checkin',
                     'guest_lookup_by_name', 'guest_checkin_volunteer',
                     'guest_checkin_by_id', 'guest_set_email')
 order by 1;

-- (c) RLS on, one policy per table.
select tablename, policyname, cmd, roles
  from pg_policies
 where schemaname = 'public'
 order by tablename;

