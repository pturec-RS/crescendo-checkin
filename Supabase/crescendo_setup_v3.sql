-- ─── volunteer_pin_check ────────────────────────────────────────────────────
-- Returns a boolean and nothing else. Callable by anon so the PIN screen can
-- validate before searching.

CREATE OR REPLACE FUNCTION public.volunteer_pin_check(p_pin text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
declare
  v_hash text;
begin
  if p_pin is null or length(p_pin) = 0 then
    return false;
  end if;

  select value into v_hash
    from public.app_settings
   where key = 'volunteer_pin_hash';

  if v_hash is null then
    return false;
  end if;

  return extensions.crypt(p_pin, v_hash) = v_hash;
end;
$function$;


-- ─── guest_lookup ───────────────────────────────────────────────────────────
-- Guest page search. Returns names and status only — NO table_number or room.
-- A search on its own reveals nothing about seating.
-- Strips empty strings from the array, so a blank email can never match.

CREATE OR REPLACE FUNCTION public.guest_lookup(p_emails text[])
 RETURNS TABLE(first_name text, last_name text, email text, checked_in boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_emails text[];
begin
  if p_emails is null or array_length(p_emails, 1) is null
     or array_length(p_emails, 1) > 10 then
    raise exception 'Invalid request';
  end if;

  select array_agg(lower(btrim(e)))
    into v_emails
    from unnest(p_emails) as e
   where length(btrim(e)) > 0;

  return query
    select r.first_name, r.last_name, r.email, r.checked_in
      from public.registrations r
     where r.email = any (v_emails);
end;
$function$;


-- ─── guest_checkin ──────────────────────────────────────────────────────────
-- Guest self check-in. Re-matches the email array server-side, so no row ids
-- cross the wire and the roster cannot be enumerated by guessing ids.
-- The `and r.checked_in = false` guard makes re-check-in a no-op that preserves
-- the original check_in_time.

CREATE OR REPLACE FUNCTION public.guest_checkin(p_emails text[])
 RETURNS TABLE(first_name text, last_name text, email text, table_number text, room text, checked_in boolean, check_in_time timestamp with time zone)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_emails text[];
begin
  if p_emails is null or array_length(p_emails, 1) is null
     or array_length(p_emails, 1) > 10 then
    raise exception 'Invalid request';
  end if;

  select array_agg(lower(btrim(e)))
    into v_emails
    from unnest(p_emails) as e
   where length(btrim(e)) > 0;

  update public.registrations r
     set checked_in     = true,
         check_in_time  = now(),
         checkin_method = 'self'
   where r.email = any (v_emails)
     and r.checked_in = false;

  return query
    select r.first_name, r.last_name, r.email,
           r.table_number, r.room, r.checked_in, r.check_in_time
      from public.registrations r
     where r.email = any (v_emails);
end;
$function$;


-- ─── guest_lookup_by_name ───────────────────────────────────────────────────
-- Volunteer name search. PIN verified server-side on EVERY call — a gate in the
-- webpage alone would be bypassable by calling this directly with the
-- publishable key.
--
-- Returns id (needed to check in guests with no email) but NO table_number or
-- room, matching guest_lookup.
--
-- Requires a last name of 2+ characters and caps at 25 rows so the roster
-- cannot be dumped. Strips % _ \ so input cannot widen the match.

CREATE OR REPLACE FUNCTION public.guest_lookup_by_name(p_pin text, p_first text, p_last text)
 RETURNS TABLE(id bigint, first_name text, last_name text, email text, checked_in boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
declare
  v_first text := lower(btrim(coalesce(p_first, '')));
  v_last  text := lower(btrim(coalesce(p_last,  '')));
begin
  if not public.volunteer_pin_check(p_pin) then
    raise exception 'Invalid request';
  end if;

  v_first := regexp_replace(v_first, '[%_\\]', '', 'g');
  v_last  := regexp_replace(v_last,  '[%_\\]', '', 'g');

  if length(v_last) < 2 then
    raise exception 'Last name must be at least 2 characters';
  end if;

  return query
  select r.id,
         r.first_name,
         r.last_name,
         r.email,
         r.checked_in
    from public.registrations r
   where lower(btrim(r.last_name)) like v_last || '%'
     and (v_first = '' or lower(btrim(r.first_name)) like v_first || '%')
   order by r.last_name, r.first_name
   limit 25;
end;
$function$;


