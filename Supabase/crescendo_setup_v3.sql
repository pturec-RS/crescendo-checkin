-- SECTION 6 — FUNCTION GRANTS
--
-- BOTH anon AND authenticated. This is not optional and is not redundant.
--
-- All three pages share a browser origin, and supabase-js persists sessions per
-- origin. If anyone signs into the admin page, other pages in that browser can
-- send the admin JWT and be evaluated as `authenticated` rather than `anon`.
-- Granting only anon produces a 42501 that is extremely hard to diagnose,
-- because the catalog will show anon holding EXECUTE the whole time.
--
-- The client pages are also configured with persistSession:false to prevent
-- this, but the grants are the belt to that suspenders.
-- ============================================================================

