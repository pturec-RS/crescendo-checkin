revoke all on function public.guest_lookup(text[])                   from public;
revoke all on function public.guest_checkin(text[])                  from public;
revoke all on function public.guest_lookup_by_name(text, text, text) from public;
revoke all on function public.guest_checkin_volunteer(text, text[])  from public;
revoke all on function public.guest_checkin_by_id(text, bigint[])    from public;
revoke all on function public.guest_set_email(text, bigint, text)    from public;

grant execute on function public.volunteer_pin_check(text)              to anon, authenticated;
grant execute on function public.guest_lookup(text[])                   to anon, authenticated;
grant execute on function public.guest_checkin(text[])                  to anon, authenticated;
grant execute on function public.guest_lookup_by_name(text, text, text) to anon, authenticated;
